# Selective rebuild: does not touch the labelling-sheet target.
p <- "data/validation/museum_affiliation_followup_2026-09-26"
targets::tar_make(names = c(museum_review_files, museum_identity_audit_file, museum_records_file, dup_museums, multisite_review, entities_file))
source("tests/testthat.R")
for (f in list.files("R", pattern = "[.]R$", full.names = TRUE)) source(f)
b <- readRDS("data/processed/affiliation_followup_before.rds")
e <- targets::tar_read(entities); r <- targets::tar_read(museum_records); a <- targets::tar_read(museum_analysis)
checks <- list()
check <- function(label, value) {
  checks[[length(checks) + 1L]] <<- tibble::tibble(check = label, passed = isTRUE(value))
  readr::write_csv(dplyr::bind_rows(checks), file.path(p, "integrity_checks.csv"))
  if (!isTRUE(value)) stop(label)
}
check("Automatic baseline unchanged", identical(e, b$entities))
check("Automatic multisite queue unchanged", identical(targets::tar_read(multisite_review), b$multisite_review))
check("Original 60002 source rows and normalized fields preserved", nrow(r) == 60002L && identical(r[names(dn_schema_normalized())], e[names(dn_schema_normalized())]))
ids <- dn_read_museum_review(file.path(p, "museum_identity_decisions_after.csv"), dn_schema_museum_identity_decisions())
d <- dn_read_museum_review(file.path(p, "museum_decisions_final.csv"), dn_schema_museum_decisions())
o <- dn_read_museum_review(file.path(p, "museum_name_overrides_after.csv"), dn_schema_museum_name_overrides())
rules <- dn_read_museum_review(file.path(p, "museum_chain_rules_before.csv"), dn_schema_chain_rules())
check("Guarded identity replay equals saved records", identical(r, dn_reconcile_museums(e, ids)$records))
check("Analysis equals replay", identical(a, dn_museum_analysis(r, rules, d, o, targets::tar_read(gazetteer))))
check("Reviewed Parquet refreshed", identical(tibble::as_tibble(arrow::read_parquet("data/processed/museum_records.parquet")), r))
check("Baseline Parquet unchanged", identical(tibble::as_tibble(arrow::read_parquet("data/processed/entities.parquet")), e))
protected <- readr::read_csv(file.path(p, "preserved_input_checksums.csv"), show_col_types = FALSE)
actual <- vapply(protected$path, function(f) digest::digest(file = f, algo = "sha256"), character(1))
check("366 protected files and original human labels unchanged", nrow(protected) == 366L && identical(unname(actual), protected$sha256))
check("Threshold unchanged", identical(DN_NAME_SIM_MIN, 0.85))
check("57272 counted source records", sum(r$counted) == 57272L)
check("52557 counted institutions and 52425 eligible", sum(a$counted) == 52557L && sum(a$analysis_eligible) == 52425L)
check("125 identity rows in 51 cases", nrow(ids) == 125L && dplyr::n_distinct(ids$case_id) == 51L)
check("39 complete reviews and 11 non-museum decisions", sum(a$review_status == "verified") == 39L && sum(a$category_decision == "not_museum") == 11L)
vegas <- a[a$source_id == "1efb0840-65fe-4aba-800d-11a5af9adc7f", ]
check("Vegas pair is one affiliated reviewed museum with preserved raw name", nrow(vegas) == 1L && vegas$review_status == "verified" && vegas$affiliation_status == "chain" && vegas$primary_name == "Madame Tussauds Las Vegas" && vegas$name_raw == b$analysis$name_raw[match(vegas$source_id, b$analysis$source_id)] && length(unique(r$entity_id[r$source_id %in% c(vegas$source_id, "8409401138")])) == 1L)
si <- a[a$name_expanded == "smithsonian institution", ]
check("Smithsonian has five parent-affiliated pending rows and three unresolved counted rows", sum(si$counted & si$affiliation_status == "chain") == 5L && sum(si$counted & si$affiliation_status == "unknown") == 3L && sum(!si$counted) == 2L)
gate <- tryCatch({dn_assert_museum_publication_ready(a, "old jail museum"); ""}, error = conditionMessage)
check("Old Jail still fails publication gate", nzchar(gate))
writeLines(gate, file.path(p, "publication_gate.txt"))
readr::write_csv(a[a$review_status == "verified", ], file.path(p, "verified_institutions.csv"), na = "")
stopifnot(file.copy("data/processed/museum_review/identity_audit.csv", file.path(p, "identity_audit_checkpoint.csv"), overwrite = TRUE))
stopifnot(file.copy("data/raw/MANIFEST.json", file.path(p, "manifest_after.json"), overwrite = TRUE))
check("All six local-operator records have consistent affiliations", all(a$affiliation_status[a$source_id %in% readr::read_csv(file.path(p, "local_operator_decisions.csv"), show_col_types = FALSE)$source_id] == "chain"))
message(length(checks), " integrity checks pass; ", nrow(protected), " protected files preserved.")

