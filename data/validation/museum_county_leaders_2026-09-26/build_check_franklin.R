# Refresh the saved pipeline and validate the Franklin sub-batch only.
packet <- "data/validation/museum_county_leaders_2026-09-26"
targets::tar_make(names = c(museum_review_files, museum_identity_audit_file,
  museum_records_file, dup_museums, multisite_review, entities_file))
source("tests/testthat.R")
for (f in list.files("R", pattern = "[.]R$", full.names = TRUE)) source(f)
before <- readRDS("data/processed/county_leaders_before.rds")
baseline <- targets::tar_read(entities)
records <- targets::tar_read(museum_records)
analysis <- targets::tar_read(museum_analysis)
checks <- list()
check <- function(label, value) {
  checks[[length(checks) + 1L]] <<- tibble::tibble(check = label, passed = isTRUE(value))
  if (!isTRUE(value)) stop(label)
}
ids <- dn_read_museum_review(file.path(packet, "franklin_identity_decisions_after.csv"), dn_schema_museum_identity_decisions())
decisions <- dn_read_museum_review(file.path(packet, "franklin_name_decisions_after.csv"), dn_schema_museum_decisions())
rules <- dn_read_museum_review(file.path(packet, "chain_rules.csv"), dn_schema_chain_rules())
replay <- dn_reconcile_museums(baseline, ids)
check("Automatic baseline unchanged", identical(baseline, before$entities))
check("Baseline multisite queue unchanged", identical(targets::tar_read(multisite_review), before$multisite_review))
check("All 60002 original source rows and normalized fields unchanged", nrow(records) == 60002L &&
  identical(records[names(dn_schema_normalized())], baseline[names(dn_schema_normalized())]))
check("Saved records match guarded replay", identical(records, replay$records))
check("Saved analysis matches replay", identical(analysis, dn_museum_analysis(replay$records, rules, decisions)))
check("Source records counted 57284", sum(records$counted) == 57284L)
check("Institutions counted 52575; eligible 52443", sum(analysis$counted) == 52575L && sum(analysis$analysis_eligible) == 52443L)
check("104 identity rows in 41 cases", nrow(ids) == 104L && dplyr::n_distinct(ids$case_id) == 41L)
check("Franklin bare-name institutions 6", sum(analysis$analysis_eligible & analysis$name_expanded == "franklin county historical society") == 6L)
check("Greene and Jackson remain 11 each", all(vapply(paste(c("greene", "jackson"), "county historical society"),
  function(nm) sum(analysis$analysis_eligible & analysis$name_expanded == nm), integer(1)) == 11L))
check("Old Jail headline remains 11 non-chain", dn_museum_ranking(analysis)$n_entities[dn_museum_ranking(analysis)$name_expanded == "old jail museum"] == 11L)
check("21 factual reviews complete, four not-museum records", sum(analysis$review_status == "verified") == 21L && sum(analysis$category_decision == "not_museum") == 4L)
check("Reviewed Parquet refreshed", identical(tibble::as_tibble(arrow::read_parquet("data/processed/museum_records.parquet")), records))
check("Baseline Parquet unchanged", identical(tibble::as_tibble(arrow::read_parquet("data/processed/entities.parquet")), baseline))
protected <- readr::read_csv(file.path(packet, "preserved_input_checksums.csv"), show_col_types = FALSE)
actual <- vapply(protected$path, function(p) digest::digest(file = p, algo = "sha256"), character(1))
check("Earlier packets and original human labels preserved", identical(unname(actual), protected$sha256))
changed <- records$source_id %in% readr::read_csv(file.path(packet, "franklin_applied_identity_decisions.csv"), show_col_types = FALSE)$source_id
check("Records outside four cases unchanged", identical(records[!changed, ], before$records[!changed, ]))
check("Threshold remains 0.85", identical(DN_NAME_SIM_MIN, 0.85))
gate_error <- tryCatch({dn_assert_museum_publication_ready(analysis, "franklin county historical society"); ""}, error = conditionMessage)
check("Unfinished Franklin group cannot pass publication gate", nzchar(gate_error))
readr::write_csv(dplyr::bind_rows(checks), file.path(packet, "franklin_integrity_checks.csv"))
writeLines(gate_error, file.path(packet, "franklin_publication_gate.txt"))
stopifnot(file.copy("data/processed/museum_review/identity_audit.csv", file.path(packet, "identity_audit_franklin_checkpoint.csv"), overwrite = TRUE))
affected_ids <- unique(records$entity_id[changed])
readr::write_csv(analysis[analysis$entity_id %in% affected_ids, ], file.path(packet, "franklin_reviewed_institutions.csv"), na = "")
readr::write_csv(records[changed, ], file.path(packet, "franklin_records_after.csv"), na = "")
message(length(checks), " integrity checks passed; ", nrow(protected), " protected files unchanged.")
