packet <- "data/validation/museum_jail_followup_2026-09-26"
targets::tar_make(names = c(museum_review_files, museum_identity_audit_file,
  museum_records_file, dup_museums, multisite_review, entities_file))
source("tests/testthat.R")
for (f in list.files("R", pattern = "[.]R$", full.names = TRUE)) source(f)
before <- readRDS("data/processed/jail_followup_before.rds")
baseline <- targets::tar_read(entities)
records <- targets::tar_read(museum_records)
analysis <- targets::tar_read(museum_analysis)
ids <- dn_read_museum_review(file.path(packet, "identity_decisions_after.csv"), dn_schema_museum_identity_decisions())
decisions <- dn_read_museum_review(file.path(packet, "name_decisions_after.csv"), dn_schema_museum_decisions())
overrides <- dn_read_museum_review(file.path(packet, "name_overrides_after.csv"), dn_schema_museum_name_overrides())
rules <- dn_read_museum_review(file.path(packet, "chain_rules.csv"), dn_schema_chain_rules())
replay <- dn_reconcile_museums(baseline, ids)
checks <- list()
check <- function(label, value) {
  checks[[length(checks) + 1L]] <<- tibble::tibble(check = label, passed = isTRUE(value))
  readr::write_csv(dplyr::bind_rows(checks), file.path(packet, "integrity_checks.csv"))
  if (!isTRUE(value)) stop(label)
}
check("Automatic baseline unchanged", identical(baseline, before$entities))
check("Automatic multisite review unchanged", identical(targets::tar_read(multisite_review), before$multisite_review))
check("60002 original source rows and normalized fields preserved", nrow(records) == 60002L && identical(records[names(dn_schema_normalized())], baseline[names(dn_schema_normalized())]))
check("Reviewed records match guarded replay", identical(records, replay$records))
check("Analysis matches guarded names and decisions", identical(analysis, dn_museum_analysis(records, rules, decisions, overrides, targets::tar_read(gazetteer))))
check("Reviewed Parquet matches saved target", identical(tibble::as_tibble(arrow::read_parquet("data/processed/museum_records.parquet")), records))
check("Baseline Parquet matches unchanged target", identical(tibble::as_tibble(arrow::read_parquet("data/processed/entities.parquet")), baseline))
protected <- readr::read_csv(file.path(packet, "preserved_input_checksums.csv"), show_col_types = FALSE)
actual <- vapply(protected$path, function(p) digest::digest(file = p, algo = "sha256"), character(1))
check("All prior packets and original human labels preserved", identical(unname(actual), protected$sha256))
changed_ids <- c("c22b0c13-6dd7-472c-9000-c32a0a87e095", "8401300390")
check("Identity rows outside Barnesville unchanged", identical(records[!records$source_id %in% changed_ids, ], before$records[!before$records$source_id %in% changed_ids, ]))
check("Threshold remains 0.85", identical(DN_NAME_SIM_MIN, 0.85))
check("57273 counted source rows", sum(records$counted) == 57273L)
check("52560 counted institutions and 52428 eligible", sum(analysis$counted) == 52560L && sum(analysis$analysis_eligible) == 52428L)
check("123 identity rows in 50 cases", nrow(ids) == 123L && dplyr::n_distinct(ids$case_id) == 50L)
check("36 complete factual reviews and nine non-museum decisions", sum(analysis$review_status == "verified") == 36L && sum(analysis$category_decision == "not_museum") == 9L)
jail <- analysis[analysis$counted & analysis$name_expanded == "old jail museum" & analysis$affiliation_status != "chain", ]
check("Eight non-chain Old Jail institutions", nrow(jail) == 8L)
gate <- tryCatch({dn_assert_museum_publication_ready(analysis, "old jail museum"); ""}, error = conditionMessage)
check("Unfinished Old Jail headline fails explicit publication gate", nzchar(gate))
writeLines(gate, file.path(packet, "publication_gate.txt"))
smethport <- analysis[analysis$source_id == "bd9c1f07-e7c7-493a-9471-a98499e86838", ]
check("Smethport preferred name and raw name both retained", smethport$name_raw == "Old Jail Museum" && smethport$primary_name == "The County Museum in The Old Jail" && smethport$source_primary_name == "Old Jail Museum" && smethport$name_expanded == "county museum in the old jail")
readr::write_csv(jail, file.path(packet, "old_jail_institutions_after.csv"), na = "")
readr::write_csv(jail[jail$review_status != "verified", ], file.path(packet, "old_jail_pending.csv"), na = "")
readr::write_csv(analysis[analysis$source_id %in% readr::read_csv(file.path(packet, "applied_name_decisions.csv"), show_col_types = FALSE)$source_id, ], file.path(packet, "reviewed_institutions_after.csv"), na = "")
stopifnot(file.copy("data/processed/museum_review/identity_audit.csv", file.path(packet, "identity_audit_checkpoint.csv"), overwrite = TRUE))
stopifnot(file.copy("data/raw/MANIFEST.json", file.path(packet, "manifest_after.json"), overwrite = TRUE))
message(length(checks), " integrity checks passed; ", nrow(protected), " protected files unchanged.")
